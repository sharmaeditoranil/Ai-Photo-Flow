    @staticmethod
    def get_machine_fingerprint() -> str:
        """
        Extracts hardware-bound identifiers from Apple Silicon / Intel Motherboard / CPU.
        Returns a unique, immutable 16-character hardware signature.
        """
        raw_hw = ""
        try:
            if platform.system() == "Darwin":
                # macOS IOPlatformExpertDevice extraction
                cmd = "ioreg -d2 -c IOPlatformExpertDevice"
                output = subprocess.check_output(cmd, shell=True, timeout=2).decode(errors="ignore")
                for line in output.split("\n"):
                    if "IOPlatformUUID" in line or "IOPlatformSerialNumber" in line:
                        raw_hw += line.strip()
            elif platform.system() == "Windows":
                # Windows Computer System Product UUID
                try:
                    cmd = 'powershell -NoProfile -Command "(Get-CimInstance -ClassName Win32_ComputerSystemProduct).UUID"'
                    raw_hw = subprocess.check_output(cmd, shell=True, timeout=2).decode(errors="ignore").strip()
                except Exception:
                    try:
                        cmd = "wmic csproduct get uuid"
                        output = subprocess.check_output(cmd, shell=True, timeout=2).decode(errors="ignore")
                        for line in output.split("\n"):
                            line = line.strip()
                            if line and "UUID" not in line:
                                raw_hw = line
                                break
                    except Exception:
                        pass
        except Exception:
            pass

        if not raw_hw:
            # Cross-platform fallback using hardware MAC node and CPU info
            raw_hw = f"{uuid.getnode()}:{platform.node()}:{platform.machine()}:{platform.processor()}"

        h = hashlib.sha256(raw_hw.encode()).hexdigest()[:16].upper()
        return f"{h[:4]}-{h[4:8]}-{h[8:12]}-{h[12:16]}"

    def _compute_security_signature(self, plan_name: str, expires_at: Optional[str], is_vip: int, max_devices: int) -> str:
        """
        Generates an unforgeable HMAC-SHA256 signature for the license row.
        If a cracker edits the SQLite DB with a DB tool, this signature will fail!
        """
        payload = f"{self.machine_id}::{plan_name}::{expires_at or 'LIFETIME'}::{is_vip}::{max_devices}"
        return hmac.new(_SECURITY_PEPPER, payload.encode("utf-8"), hashlib.sha256).hexdigest()

