        activated_at_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        now_ts = int(time.time())

        # Generate tamper-proof cryptographic signature
        sig = self._compute_security_signature(plan_name, expires_at_str, is_vip, max_devices)

        conn = get_connection()
