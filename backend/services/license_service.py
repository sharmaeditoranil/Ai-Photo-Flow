    def verify_coupon(self, code: str, plan_id: str, billing_cycle: str, currency: str = "INR") -> Dict[str, Any]:
        code_clean = (code or "").strip().upper()
        conn = get_connection()
        cursor = conn.cursor()
        cursor.execute("SELECT code, discount_percent, is_active, notes FROM coupons WHERE UPPER(code) = ?", (code_clean,))
        row = cursor.fetchone()
        conn.close()

        if not row or not row["is_active"]:
            return {"valid": False, "message": "Invalid or expired referral/coupon code"}

        discount_pct = float(row["discount_percent"])
        currency = currency.upper() if currency in ("INR", "USD") else "INR"
        plan_id = plan_id.upper()
        cycle = billing_cycle.lower()

        prices = PRICING_CATALOG.get(currency, PRICING_CATALOG["INR"])
        plan_pricing = prices.get(plan_id, prices["PRO"])
        base_price = plan_pricing.get(cycle, plan_pricing.get("yearly", 11999))

        discount_amount = round((base_price * discount_pct) / 100.0)
        final_price = max(0, base_price - discount_amount)

        return {
            "valid": True,
            "code": row["code"],
            "discount_percent": discount_pct,
            "original_price": base_price,
            "discount_amount": discount_amount,
            "final_price": final_price,
            "currency": currency,
            "notes": row["notes"],
            "message": f"{int(discount_pct)}% referral discount successfully applied!"
        }
