    @staticmethod
    def generate_cryptographic_key(plan_type: str, days: int, client_token: str) -> str:
        """
        Creates a mathematically signed license key with embedded HMAC checksum:
        Format: APF-{PLAN}-{DAYS}-{TOKEN}-{CHECKSUM}
        """
        clean_plan = plan_type.upper()
        clean_token = client_token.upper()[:6] or "RETAIL"
        raw_msg = f"{clean_plan}:{days}:{clean_token}"
        sig = hmac.new(_SECURITY_PEPPER, raw_msg.encode("utf-8"), hashlib.sha256).hexdigest()[:8].upper()
        return f"APF-{clean_plan}-{days}-{clean_token}-{sig}"

    @staticmethod
    def verify_cryptographic_key(key: str) -> Tuple[bool, str, int, str]:
        """
        Verifies the mathematical signature of a license key.
        Cracked or random keys will fail here.
        """
        clean_key = (key or "").strip().upper()
        parts = clean_key.split("-")
        if len(parts) < 5 or parts[0] != "APF":
            return False, "", 0, "Invalid key format"

        plan = parts[1]
        try:
            days = int(parts[2])
        except ValueError:
            return False, "", 0, "Invalid key duration"

        token = parts[3]
        sig = parts[4]

        # Verify mathematical checksum
        raw_msg = f"{plan}:{days}:{token}"
        expected_sig = hmac.new(_SECURITY_PEPPER, raw_msg.encode("utf-8"), hashlib.sha256).hexdigest()[:8].upper()

        if sig != expected_sig:
            return False, "", 0, "License Key Checksum Signature Failed (Counterfeit/Forged Key)"

        return True, plan, days, "Valid"

