    def verify_tamper_integrity(self) -> Tuple[bool, str, Dict[str, Any]]:
        """
        Anti-Crack & Anti-Tamper Security Verification:
        1. Checks database signature against embedded cryptographic salt.
        2. Detects computer clock rollback manipulation.
        3. Validates hardware machine ID binding.
        """
        conn = get_connection()
        cursor = conn.cursor()
        cursor.execute("""
        SELECT plan_name, license_key, status, is_vip, user_name, user_email, max_devices,
               machine_id, security_signature, last_known_ts, expires_at, activated_at
        FROM license_state WHERE id = 1
        """)
        row = cursor.fetchone()

        if not row:
            conn.close()
            return False, "License state missing", {}

        now_ts = int(time.time())
        last_known_ts = row["last_known_ts"] or 0

        # Anti-Clock Rollback Check:
        # If user changed system clock backwards by more than 1 hour to prevent expiry
        if now_ts < (last_known_ts - 3600):
            conn.close()
            return False, "Clock tampering detected! Please correct your computer's system date and time.", {
                "plan": "LOCKED",
                "status": "TAMPER_DETECTED",
                "is_active": False,
                "days_left": 0
            }

        # Update last known timestamp
        cursor.execute("UPDATE license_state SET last_known_ts = ? WHERE id = 1", (max(now_ts, last_known_ts),))
        conn.commit()
        conn.close()

        plan_name = row["plan_name"]
        is_vip = bool(row["is_vip"])
        expires_at_str = row["expires_at"]
        max_devices = row["max_devices"] or 1
        stored_sig = row["security_signature"]
        stored_machine = row["machine_id"]

        # 1. Cryptographic DB Tamper Check
        expected_sig = self._compute_security_signature(plan_name, expires_at_str, 1 if is_vip else 0, max_devices)
        if stored_sig != expected_sig:
            return False, "Software tampering detected! Database signature invalid.", {
                "plan": "LOCKED",
                "status": "TAMPER_DETECTED",
                "is_active": False,
                "days_left": 0
            }

        # 2. Hardware Machine Binding Check
        if stored_machine and stored_machine != self.machine_id and not is_vip:
            return False, "Hardware license mismatch! License is bound to another device.", {
                "plan": "LOCKED",
                "status": "DEVICE_MISMATCH",
                "is_active": False,
                "days_left": 0
            }

        # 3. Expiry Check
        days_left = 9999
        status = row["status"]
        if expires_at_str:
            try:
                exp_date = datetime.strptime(expires_at_str, "%Y-%m-%d %H:%M:%S")
                delta = exp_date - datetime.now()
                days_left = max(0, delta.days)
                if delta.total_seconds() <= 0:
                    status = "EXPIRED"
                else:
                    status = "ACTIVE"
            except Exception:
                status = "EXPIRED"

        return True, "License valid and secure", {
            "plan": plan_name,
            "status": status,
            "is_active": status == "ACTIVE",
            "is_vip": is_vip,
            "days_left": days_left,
            "expires_at": expires_at_str,
            "user_name": row["user_name"],
            "user_email": row["user_email"],
            "license_key": row["license_key"],
            "machine_id": self.machine_id,
            "max_devices": max_devices,
            "security_verified": True,
            "features": {
                "unlimited_photos": plan_name in ("PRO", "STUDIO", "VIP_LIFETIME"),
                "high_res_export": status == "ACTIVE",
                "indian_skin_tone": True,
                "multi_device": plan_name == "STUDIO",
                "batch_auto_edit": True,
                "all_culling_rules": True
            }
        }

